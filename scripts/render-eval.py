#!/usr/bin/env python3
"""Render docs/eval-results.md from the scored runs under evals/results.

    python3 scripts/render-eval.py [evals/results] [docs/eval-results.md]

Rows whose upstream was the scripted mock are listed separately and marked, so
a harness smoke test can never be read as a measurement of a model.
"""
import json
import pathlib
import sys
from datetime import datetime, timezone

HEADER = """# Evaluation results

Generated by `scripts/render-eval.py` from the scored runs in `evals/results/`.
Do not hand-edit.

The question this answers is whether Codex plus this bridge beats native OpenCode
on **cost per confirmed finding**, which is the only comparison that decides
whether the bridge stays the default.

`evals/idor-app` is a seeded local target with one deliberate IDOR on
`/v2/orders/{id}` and a control next to it (`/v2/orders/{id}/receipt`, which does
check ownership). A finding against the control is scored as a false positive.
"""


def main():
    results_dir = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "evals/results")
    out_path = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else "docs/eval-results.md")

    runs = []
    for score_path in sorted(results_dir.glob("*/score.json")):
        runs.append(json.loads(score_path.read_text()))

    real = [r for r in runs if r.get("counts_as_result")]
    # A smoke test is a run that actually executed against the scripted
    # upstream. A run that never started is blocked, and belongs only in the
    # blocked table.
    smoke = [r for r in runs if r.get("upstream") == "mock"]
    blocked = [r for r in runs if not r.get("counts_as_result") and r.get("upstream") != "mock"]

    lines = [HEADER, ""]
    lines.append(f"Generated {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}.")
    lines.append("")

    lines.append("## Results")
    lines.append("")
    if real:
        lines.append("| harness | target | upstream | confirmed | false positives | tokens | cost | cost per confirmed |")
        lines.append("|---|---|---|---|---|---|---|---|")
        for r in real:
            lines.append("| {} | {} | {} | {} | {} | {} | {} | {} |".format(
                r.get("harness"), r.get("target"), r.get("upstream"),
                r.get("confirmed"), r.get("false_positives"),
                fmt(r.get("tokens")), fmt(r.get("cost_usd")), fmt(r.get("cost_per_confirmed"))))
    else:
        lines.append("**No scored runs yet.** Every harness below is blocked, so the")
        lines.append("comparison the plan asks for cannot be made and the bridge has no")
        lines.append("numbers behind it.")
    lines.append("")

    lines.append("## Blocked")
    lines.append("")
    if real:
        lines.append("Nothing is blocked for the harnesses listed above.")
    else:
        lines.append("| harness | target | upstream | reason |")
        lines.append("|---|---|---|---|")

        for r in blocked:
            lines.append("| {} | {} | {} | {} |".format(
                r.get("harness"), r.get("target"), r.get("upstream"), r.get("blocked_reason")))
    lines.append("")

    lines.append("## Harness smoke tests")
    lines.append("")
    lines.append("These runs used the scripted local upstream. They prove the harness")
    lines.append("works end to end — scope enforcement, schema-constrained findings,")
    lines.append("scoring — and they measure **nothing** about a model, because the")
    lines.append("findings are the ones the script asked for.")
    lines.append("")
    if smoke:
        lines.append("| harness | target | upstream | confirmed | false positives | note |")
        lines.append("|---|---|---|---|---|---|")
        for r in smoke:
            lines.append("| {} | {} | {} | {} | {} | {} |".format(
                r.get("harness"), r.get("target"), r.get("upstream"),
                r.get("confirmed"), r.get("false_positives"), r.get("blocked_reason")))
    else:
        lines.append("None recorded.")
    lines.append("")

    lines.append("## How to unblock")
    lines.append("")
    lines.append("1. Supply a working OpenCode Go API key (`ocgo setup`). The key present")
    lines.append("   on this machine returns `401 Invalid API key` from")
    lines.append("   `https://opencode.ai/zen/go/v1/chat/completions`, across `Authorization:")
    lines.append("   Bearer`, bare `Authorization` and `x-api-key`, on both the Go and Zen")
    lines.append("   paths.")
    lines.append("2. Run the three harnesses against the seeded target:")
    lines.append("")
    lines.append("   ```bash")
    lines.append("   evals/run-eval.sh bridge   idor-app")
    lines.append("   evals/run-eval.sh opencode idor-app")
    lines.append("   evals/run-eval.sh claude   idor-app")
    lines.append("   ```")
    lines.append("")
    lines.append("3. Regenerate this file: `python3 scripts/render-eval.py`.")
    lines.append("")
    lines.append("The owner-supplied targets the plan also calls for — one or two past")
    lines.append("reported findings, sanitised, and a web7 Foundry fork — are not present")
    lines.append("on this machine and are not invented here. Add them to")
    lines.append("`evals/targets.json` when they are available.")

    out_path.write_text("\n".join(lines) + "\n")
    print(f"wrote {out_path} from {len(runs)} run(s): {len(real)} scored, {len(smoke)} smoke")


def fmt(value):
    if value is None:
        return "unknown"
    if isinstance(value, float):
        return f"{value:.6f}"
    return str(value)


if __name__ == "__main__":
    sys.exit(main())
