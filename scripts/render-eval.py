#!/usr/bin/env python3
"""Render docs/eval-results.md from the scored runs under evals/results.

    python3 scripts/render-eval.py [evals/results] [docs/eval-results.md]

Rows whose upstream was the scripted mock are listed separately and marked, so
a harness smoke test can never be read as a measurement of a model.
"""
import json
import pathlib
import sys
from datetime import datetime, timezone

HEADER = """# Evaluation results

Generated by `scripts/render-eval.py` from the scored runs in `evals/results/`.
Running it replaces this file, so keep the narrative in the header rather than
hand-editing the output.

The question is whether Codex plus this bridge beats native OpenCode on cost per
confirmed finding, which is the only number that decides whether the bridge is
worth keeping.

`evals/idor-app` is a local target with one deliberate access control bug on
`/v2/orders/{id}` and a control next to it, `/v2/orders/{id}/receipt`, which does
check who is asking. A finding against the control is scored as a false
positive. Answer shape is reported separately from the security result, because
a correct answer in the wrong wrapper is a success and a failure at once.
"""


def main():
    results_dir = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "evals/results")
    out_path = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else "docs/eval-results.md")

    runs = []
    for score_path in sorted(results_dir.glob("*/score.json")):
        runs.append(json.loads(score_path.read_text()))

    real = [r for r in runs if r.get("counts_as_result")]
    # A smoke test is a run that actually executed against the scripted
    # upstream. A run that never started is blocked, and belongs only in the
    # blocked table.
    smoke = [r for r in runs if r.get("upstream") == "mock"]
    blocked = [r for r in runs if not r.get("counts_as_result") and r.get("upstream") != "mock"]

    lines = [HEADER, ""]
    lines.append(f"Generated {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}.")
    lines.append("")

    lines.append("## Results")
    lines.append("")
    if real:
        lines.append("| harness | target | upstream | schema conformant | confirmed | false positives | tokens | cost | cost per confirmed |")
        lines.append("|---|---|---|---|---|---|---|---|---|")
        for r in real:
            lines.append("| {} | {} | {} | {} | {} | {} | {} | {} | {} |".format(
                r.get("harness"), r.get("target"), r.get("upstream"),
                yesno(r.get("schema_conformant")),
                r.get("confirmed"), r.get("false_positives"),
                fmt(r.get("tokens")), fmt(r.get("cost_usd")), fmt(r.get("cost_per_confirmed"))))
    else:
        lines.append("**No scored runs yet.** Nothing below is a measurement of a model.")

    lines.append("Schema conformance is reported next to the security result on purpose:")
    lines.append("a run that finds the defect but returns it wrapped in prose has")
    lines.append("answered the security question and failed the output contract, and")
    lines.append("collapsing the two would hide one of them.")
    lines.append("")

    lines.append("## Blocked")
    lines.append("")
    if blocked:
        lines.append("| harness | target | upstream | reason |")
        lines.append("|---|---|---|---|")
        for r in blocked:
            lines.append("| {} | {} | {} | {} |".format(
                r.get("harness"), r.get("target"), r.get("upstream"), r.get("blocked_reason")))
    else:
        lines.append("Nothing is blocked.")
    lines.append("")

    lines.append("## Harness smoke tests")
    lines.append("")
    lines.append("These runs used the scripted local upstream. They show the harness")
    lines.append("works end to end: the scope guard, the required answer shape and the")
    lines.append("scoring. They measure nothing about a model, because the answers are")
    lines.append("the ones the script asked for.")
    lines.append("")
    if smoke:
        lines.append("| harness | target | upstream | confirmed | false positives | note |")
        lines.append("|---|---|---|---|---|---|")
        for r in smoke:
            lines.append("| {} | {} | {} | {} | {} | {} |".format(
                r.get("harness"), r.get("target"), r.get("upstream"),
                r.get("confirmed"), r.get("false_positives"), r.get("blocked_reason")))
    else:
        lines.append("None recorded.")
    lines.append("")

    lines.append("## How these were produced")
    lines.append("")
    lines.append("The credential is an OpenCode session token against")
    lines.append("`https://opencode.ai/inference/go/openai/v1`, sent with both")
    lines.append("`x-opencode-org-id` and `x-opencode-session`. The older")
    lines.append("`https://opencode.ai/zen/go` inference path rejects this credential")
    lines.append("with `401 Invalid API key`; only the model listing still answers there.")
    lines.append("")
    lines.append("```bash")
    lines.append("evals/run-eval.sh bridge   idor-app")
    lines.append("evals/run-eval.sh opencode idor-app")
    lines.append("evals/run-eval.sh claude   idor-app")
    lines.append("python3 scripts/render-eval.py")
    lines.append("```")
    lines.append("")
    lines.append("`evals/idor-app` is a seeded local target with one deliberate IDOR on")
    lines.append("`/v2/orders/{id}` and a control next to it. A finding against the")
    lines.append("control is scored as a false positive.")
    lines.append("")
    lines.append("Other targets are not included here. Past findings and a local")
    lines.append("blockchain fork would make the comparison stronger, but they are not")
    lines.append("present on the machine this was built on and have not been invented.")
    lines.append("Add them to `evals/targets.json` when they are available.")

    out_path.write_text("\n".join(lines) + "\n")
    print(f"wrote {out_path} from {len(runs)} run(s): {len(real)} scored, {len(smoke)} smoke")

def yesno(value):
    if value is None:
        return "unknown"
    return "yes" if value else "no"


def fmt(value):
    if value is None:
        return "unknown"
    if isinstance(value, float):
        return f"{value:.6f}"
    return str(value)


if __name__ == "__main__":
    sys.exit(main())
